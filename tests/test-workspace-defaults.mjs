import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { setWorkspaceRoot } from '../src/core/workspace.js';
import { detectProjectLanguages } from '../src/project-language.js';
import { preflightEnvironment } from '../src/environment.js';
import { runToolchain } from '../src/toolchains.js';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'kian-defaults-'));
fs.writeFileSync(path.join(root, 'package.json'), '{}');
setWorkspaceRoot(root);
let pass = 0; let fail = 0;
const check = (label, ok) => { if (ok) { pass++; console.log(`PASS ${label}`); } else { fail++; console.log(`FAIL ${label}`); } };
check('language detection uses workspace', detectProjectLanguages()[0]?.language === 'javascript');
const env = await preflightEnvironment({ paths: { read: ['package.json'] } });
check('environment preflight uses workspace', env.status === 'ready');
const result = await runToolchain('javascript', 'process.stdout.write(process.cwd())');
check('toolchain uses workspace', result.ok && result.stdout === root);
fs.rmSync(root, { recursive: true, force: true });
console.log(`=== HASIL WORKSPACE-DEFAULTS: ${pass} pass, ${fail} fail ===`);
if (fail) process.exit(1);
